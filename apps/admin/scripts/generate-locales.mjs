Object.assign(OVERRIDES, REST_OVERRIDES);

const LOCALES = ["en-US", "tr-TR", "zh-CN", "es-ES", "hi-IN"];

function buildLocale(locale) {
  const en = LOCALE_DATA["en-US"];
  const result = {};
  for (const ns of NAMESPACES) {
    const base = en[ns] ?? {};
    const overrides = locale === "en-US" ? {} : OVERRIDES[locale]?.[ns] ?? {};
    result[ns] = merge(base, overrides);
  }
  return result;
}

for (const locale of LOCALES) {
  const dir = join(localesDir, locale);
  mkdirSync(dir, { recursive: true });
  const data = buildLocale(locale);
  for (const ns of NAMESPACES) {
    const path = join(dir, `${ns}.json`);
    writeFileSync(path, `${JSON.stringify(data[ns], null, 2)}\n`, "utf8");
  }
}

